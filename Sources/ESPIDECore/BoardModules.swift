import Foundation

/// Type stubs for modules that exist only on the board, such as a `secrets.py` kept out of the
/// project on purpose. The board imports the module and reports each public name with its type
/// name; values never leave the board.
public enum BoardModules {
    /// Top-level modules the sources import (`import a.b` → `a`, `from x import y` → `x`).
    public static func imports(in sources: [String]) -> Set<String> {
        let regex = try! NSRegularExpression(pattern: #"^\s*(?:from\s+([A-Za-z_]\w*)|import\s+([A-Za-z_]\w*))"#,
                                             options: .anchorsMatchLines)
        var names = Set<String>()
        for source in sources {
            let ns = source as NSString
            for match in regex.matches(in: source, range: NSRange(location: 0, length: ns.length)) {
                for group in 1...2 where match.range(at: group).location != NSNotFound {
                    names.insert(ns.substring(with: match.range(at: group)))
                }
            }
        }
        return names
    }

    /// Board-only modules worth describing: imported by the project, present at the board's root
    /// (or /lib) as a .py file, and missing from the project. Never main.py / boot.py.
    public static func candidates(imported: Set<String>, boardFiles: [DeviceFile], localModules: Set<String>) -> [String] {
        func flatten(_ files: [DeviceFile]) -> [DeviceFile] { files.flatMap { [$0] + flatten($0.children ?? []) } }
        let onBoard = Set(flatten(boardFiles).compactMap { file -> String? in
            let parent = (file.path as NSString).deletingLastPathComponent
            guard !file.isDirectory, file.path.hasSuffix(".py"), parent == "/" || parent == "/lib" else { return nil }
            return String(file.name.dropLast(3))
        })
        return onBoard.intersection(imported).subtracting(localModules).subtracting(["main", "boot"]).sorted()
    }

    /// Prints `name type` for each public attribute of the module, then forgets it.
    public static func describeScript(_ module: String) -> String {
        """
        import sys
        _m = __import__(\(DeviceFiles.literal(module)))
        for _n in dir(_m):
            if not _n.startswith('_'):
                print(_n, type(getattr(_m, _n)).__name__)
        del _m, _n
        sys.modules.pop(\(DeviceFiles.literal(module)), None)
        """
    }

    /// A .pyi for the reported names.
    public static func stub(fromDescription output: String, module: String) -> String {
        var lines = ["# Generated by ESPIDE from \(module).py on the board: names and types only.", "from typing import Any", ""]
        for line in output.split(whereSeparator: \.isNewline) {
            let parts = line.split(separator: " ")
            guard parts.count == 2, parts[0].allSatisfy({ $0.isLetter || $0.isNumber || $0 == "_" }) else { continue }
            let name = String(parts[0])
            switch parts[1] {
            case "int", "float", "str", "bool", "bytes", "bytearray", "list", "dict", "tuple", "set":
                lines.append("\(name): \(parts[1])")
            case "function", "bound_method", "closure":
                lines.append("def \(name)(*args: Any, **kwargs: Any) -> Any: ...")
            case "type":
                lines.append("class \(name):\n    def __init__(self, *args: Any, **kwargs: Any) -> None: ...\n    def __getattr__(self, name: str) -> Any: ...")
            case "module":
                continue
            default:
                lines.append("\(name): Any")
            }
        }
        return lines.joined(separator: "\n") + "\n"
    }
}
